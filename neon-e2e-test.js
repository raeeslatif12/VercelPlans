import 'dotenv/config';
import crypto from 'node:crypto';
import pg from 'pg';

const base = process.env.BASE_URL || `http://localhost:${process.env.PORT || 3000}`;
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
const randomPhone = () => `03${crypto.randomInt(100000000, 999999999)}`;
const randomPassword = () => `${crypto.randomBytes(18).toString('base64url')}Aa1!`;
const registrationBody = (phone, password, extra = {}) => ({ phone, password, firstName: 'Neon', lastName: 'Tester', ...extra });
const request = async (path, options = {}, cookie = '') => {
  const response = await fetch(`${base}${path}`, { ...options, headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}), ...(options.headers || {}) } });
  const data = await response.json().catch(() => ({}));
  const setCookie = response.headers.get('set-cookie');
  return { response, data, cookie: setCookie ? setCookie.split(';')[0] : cookie };
};
const post = (path, body, cookie) => request(path, { method: 'POST', body: JSON.stringify(body) }, cookie);
const patch = (path, body, cookie) => request(path, { method: 'PATCH', body: JSON.stringify(body) }, cookie);
const assert = (condition, message) => { if (!condition) throw new Error(message); };

let userId;
let secondUserId;
let deviceSecondId;
let deviceThirdId;
let adminCreatedId;
let adminCreatedPhone;
let adminCreatedPassword;
let e2eDeviceHash;
let orderId;
let qualifiedOrderId;
let withdrawalId;
let tempPlanId;
let tempMethodId;
try {
  await pool.query("INSERT INTO app_settings(setting_name, setting_value) VALUES('max_accounts_per_device', '1') ON CONFLICT(setting_name) DO UPDATE SET setting_value = '1'");
  const phone = randomPhone();
  const password = randomPassword();
  const testDeviceIp = `198.51.100.${crypto.randomInt(1, 250)}`;
  const registered = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': testDeviceIp }, body: JSON.stringify(registrationBody(phone, password)) });
  assert(registered.response.status === 201, `registration failed (${registered.response.status}): ${registered.data.error || 'no error returned'}`);
  userId = registered.data.user.id;
  let userCookie = registered.cookie;
  const blockedSameDevice = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': testDeviceIp }, body: JSON.stringify(registrationBody(randomPhone(), randomPassword())) });
  assert(blockedSameDevice.response.status === 409, 'same-device registration bypassed the default limit');
  const referralCode = registered.data.user.referralCode;
  assert(/^[A-F0-9]{8}$/.test(referralCode), `invalid referral code format: ${referralCode}`);
  const invalidReferral = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': `198.51.102.${crypto.randomInt(1, 250)}` }, body: JSON.stringify(registrationBody(randomPhone(), randomPassword(), { referralCode: 'INVALID1' })) });
  assert(invalidReferral.response.status === 400 && invalidReferral.data.error === 'Invalid referral code.', 'invalid referral code was accepted');
  const selfReferral = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': `198.51.103.${crypto.randomInt(1, 250)}` }, body: JSON.stringify(registrationBody(phone, randomPassword(), { referralCode })) });
  assert(selfReferral.response.status === 400 && selfReferral.data.error === 'You cannot use your own referral code.', 'self referral was not rejected');
  const referredPhone = randomPhone();
  const referredPassword = randomPassword();
  const referred = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': `198.51.101.${crypto.randomInt(1, 250)}` }, body: JSON.stringify(registrationBody(referredPhone, referredPassword, { referralCode })) });
  assert(referred.response.status === 201, 'referred registration failed');
  secondUserId = referred.data.user.id;
  assert(referred.data.user.referralCode && referred.data.user.referralCode !== referralCode, 'users did not receive distinct referral codes');
  const referralRows = (await pool.query('SELECT id,referred_by FROM users WHERE id=$1', [secondUserId])).rows[0];
  const referralStatus = (await pool.query('SELECT status,rewarded_at FROM referral_rewards WHERE referred_user_id=$1', [secondUserId])).rows[0];
  const referrerRows = (await pool.query('SELECT total_referrals,referral_earnings FROM users WHERE id=$1', [userId])).rows[0];
  const referrerSession = (await request('/api/session', {}, userCookie)).data.user;
  assert(referralRows.referred_by === userId, `referral relationship was not persisted (${userId},${secondUserId},${referralRows.referred_by})`);
  assert(referralStatus.status === 'registered' && !referralStatus.rewarded_at, 'referral was rewarded before an approved order');
  assert(referrerRows.total_referrals === 1 && referrerRows.referral_earnings === 0, 'referral signup must not issue a reward');
  const session = await request('/api/session', {}, userCookie);
  assert(session.data.user.id === userId, 'session failed');
  const loggedOut = await post('/api/logout', {}, userCookie);
  assert(loggedOut.response.ok, 'logout failed');
  const loggedIn = await post('/api/login', { phone, password });
  assert(loggedIn.response.ok, 'login failed');
  userCookie = loggedIn.cookie;

  const tasks = await request('/api/tasks', {}, userCookie);
  assert(tasks.data.tasks.length === Number(tasks.data.taskCount) && tasks.data.enabled, 'tasks did not load');
  const balanceBeforeTask = Number((await pool.query('SELECT balance FROM users WHERE id=$1', [userId])).rows[0].balance);
  const completed = await post('/api/tasks/complete', {}, userCookie);
  assert(completed.response.ok, 'task completion failed');
  const balanceAfterTask = (await pool.query('SELECT balance FROM users WHERE id=$1', [userId])).rows[0].balance;
  const expectedTaskBalance = Number(tasks.data.totalReward);
  assert(balanceAfterTask === balanceBeforeTask + expectedTaskBalance, `task reward was not persisted (${balanceAfterTask} !== ${balanceBeforeTask + expectedTaskBalance})`);

  const plans = await request('/api/plans', {}, userCookie);
  assert(plans.data.plans.length > 0, 'plans did not load from PostgreSQL');
  const plan = plans.data.plans[0];
  const details = await request(`/api/plans/${plan.id}`, {}, userCookie);
  assert(details.data.paymentMethods.length > 0, 'payment methods did not load');
  const createdOrder = await post('/api/orders', { planId: plan.id, paymentMethodId: details.data.paymentMethods[0].id, paymentReference: 'E2E-REFERENCE', paymentDetails: 'E2E wallet details', paymentProof: 'data:image/jpeg;base64,/9j/AA==' }, userCookie);
  assert(createdOrder.response.status === 201, 'order creation failed');
  orderId = createdOrder.data.orderId;
  const dbOrder = (await pool.query('SELECT user_id,status FROM orders WHERE id=$1', [orderId])).rows[0];
  assert(dbOrder.user_id === userId && dbOrder.status === 'Pending', 'order was not persisted as pending');
  const userOrders = await request('/api/orders', {}, userCookie);
  assert(userOrders.data.orders.some(order => order.id === orderId), 'user order list failed');

  const secondOrders = await request('/api/orders', {}, referred.cookie);
  assert(secondOrders.data.orders.every(order => order.user_id === secondUserId), 'order isolation failed');

  const adminLogin = await post('/api/admin/login', { email: process.env.ADMIN_EMAIL || process.env.ADMIN_PHONE, password: process.env.ADMIN_PASSWORD });
  assert(adminLogin.response.ok, 'admin login failed');
  const adminCookie = adminLogin.cookie;
  const adminSession = await request('/api/admin/session', {}, adminCookie);
  assert(adminSession.response.ok, 'admin session failed');
  const limitUpdate = await request('/api/admin/settings', { method: 'PUT', body: JSON.stringify({ max_accounts_per_device: 2 }) }, adminCookie);
  assert(limitUpdate.response.ok && Number(limitUpdate.data.settings.max_accounts_per_device) === 2, 'admin device limit update failed');
  const sameDeviceSecond = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': testDeviceIp }, body: JSON.stringify(registrationBody(randomPhone(), randomPassword())) });
  assert(sameDeviceSecond.response.status === 201, 'admin limit of two did not allow the second device account');
  deviceSecondId = sameDeviceSecond.data.user.id;
  const deviceHash = (await pool.query('SELECT device_hash FROM user_devices WHERE user_id = $1 LIMIT 1', [userId])).rows[0].device_hash;
  e2eDeviceHash = deviceHash;
  const deviceCountAfterSecond = Number((await pool.query('SELECT COUNT(*)::int AS count FROM user_devices WHERE device_hash = $1', [deviceHash])).rows[0].count);
  assert(deviceCountAfterSecond === 2, 'device registration history did not record both accounts');
  adminCreatedPhone = randomPhone();
  adminCreatedPassword = randomPassword();
  const adminCreated = await post('/api/admin/users', { name: 'E2E Created User', phone: adminCreatedPhone, email: `e2e-${Date.now()}@example.invalid`, password: adminCreatedPassword, status: 'active' }, adminCookie);
  assert(adminCreated.response.status === 201 && adminCreated.data.user && !adminCreated.data.user.password_hash, 'admin-created user response exposed an invalid password field');
  adminCreatedId = adminCreated.data.user.id;
  const createdLogin = await post('/api/login', { phone: adminCreatedPhone, password: adminCreatedPassword });
  assert(createdLogin.response.ok, 'admin-created user could not log in');
  const resetPassword = randomPassword();
  const reset = await patch(`/api/admin/users/${adminCreatedId}`, { password: resetPassword }, adminCookie);
  assert(reset.response.ok && !reset.data.user.password_hash, 'admin password reset exposed password data');
  const resetLogin = await post('/api/login', { phone: adminCreatedPhone, password: resetPassword });
  assert(resetLogin.response.ok, 'admin password reset did not work');
  const referredOrder = await post('/api/orders', { planId: plan.id, paymentMethodId: details.data.paymentMethods[0].id, paymentReference: 'E2E-REFERRAL-ORDER', paymentDetails: 'E2E referral wallet', paymentProof: 'data:image/png;base64,iVBORw0KGgo=' }, referred.cookie);
  assert(referredOrder.response.status === 201, 'referred order creation failed');
  qualifiedOrderId = referredOrder.data.orderId;
  const balanceBeforeReferralReward = Number((await pool.query('SELECT balance FROM users WHERE id=$1', [userId])).rows[0].balance);
  await patch(`/api/admin/orders/${qualifiedOrderId}`, { status: 'Approved' }, adminCookie);
  const qualifiedReferral = (await pool.query('SELECT status,reward_amount FROM referral_rewards WHERE referred_user_id=$1', [secondUserId])).rows[0];
  assert(['rewarded','credited'].includes(qualifiedReferral.status) && Number(qualifiedReferral.reward_amount) === 80, 'referral was not rewarded after approval');
  const balanceAfterReferralReward = Number((await pool.query('SELECT balance FROM users WHERE id=$1', [userId])).rows[0].balance);
  assert(balanceAfterReferralReward === balanceBeforeReferralReward + 80, 'referral reward amount was not credited exactly once');
  const referralNotifications = await request('/api/notifications', {}, userCookie);
  assert(referralNotifications.response.ok, 'user notifications endpoint failed');
  const referralNotification = referralNotifications.data.notifications.find(item => item.source === 'referral_reward');
  assert(referralNotification && Number(referralNotification.amount) === 80 && referralNotification.status === 'unread', 'referral earnings notification was not created');
  await request(`/api/notifications/${referralNotification.id}/read`, { method: 'PATCH' }, userCookie);
  const updatedReferralNotification = await request('/api/notifications', {}, userCookie);
  assert(updatedReferralNotification.data.notifications.find(item => item.id === referralNotification.id)?.status === 'read', 'notification read state did not persist');
  await patch(`/api/admin/orders/${qualifiedOrderId}`, { status: 'Approved' }, adminCookie);
  const rewardCount = (await pool.query("SELECT COUNT(*)::int AS count FROM ledger_transactions WHERE source='referral_reward' AND reference=$1", [`referral:${(await pool.query('SELECT id FROM referral_rewards WHERE referred_user_id=$1', [secondUserId])).rows[0].id}`])).rows[0].count;
  const notificationCount = (await pool.query("SELECT COUNT(*)::int AS count FROM user_notifications WHERE user_id=$1 AND source='referral_reward' AND reference=$2", [userId, `referral:${(await pool.query('SELECT id FROM referral_rewards WHERE referred_user_id=$1', [secondUserId])).rows[0].id}`])).rows[0].count;
  assert(rewardCount === 1, 'referral approval was not idempotent');
  assert(notificationCount === 1, 'referral notification was duplicated on repeat credit');
  const adminOrders = await request('/api/admin/orders', {}, adminCookie);
  assert(adminOrders.data.orders.some(order => order.id === orderId), 'admin order list failed');
  await patch(`/api/admin/orders/${orderId}`, { status: 'Approved', adminNote: 'Verified in automated test' }, adminCookie);
  const approvedOrders = await request('/api/orders', {}, userCookie);
  const approvedOrder = approvedOrders.data.orders.find(order => order.id === orderId);
  assert(approvedOrder && approvedOrder.status === 'Approved', 'order status did not update for user');
  await pool.query('UPDATE users SET balance=5000 WHERE id=$1', [userId]);
  const withdrawal = await post('/api/withdrawals', { wallet: 'Easypaisa', accountNumber: '03000000000', accountHolder: 'E2E Test', amount: 2500 }, userCookie);
  assert(withdrawal.response.ok, 'withdrawal creation failed');
  withdrawalId = (await pool.query('SELECT id FROM withdrawals WHERE user_id=$1 ORDER BY id DESC LIMIT 1', [userId])).rows[0].id;
  const adminWithdrawals = await request('/api/admin/withdrawals', {}, adminCookie);
  assert(adminWithdrawals.data.withdrawals.some(item => item.id === withdrawalId), 'admin withdrawal list failed');
  const processed = await patch(`/api/admin/withdrawals/${withdrawalId}`, { status: 'Processing' }, adminCookie);
  assert(processed.response.ok, `admin withdrawal update failed (${processed.response.status}): ${processed.data.error || 'unknown error'}`);
  const userWithdrawals = await request('/api/withdrawals', {}, userCookie);
  const processedWithdrawal = userWithdrawals.data.withdrawals.find(item => item.id === withdrawalId);
  assert(processedWithdrawal && String(processedWithdrawal.status).toLowerCase() === 'processing', `withdrawal status did not update (${JSON.stringify(processedWithdrawal || null)})`);
  const methods = await request('/api/admin/payment-methods', {}, adminCookie);
  assert(methods.data.methods.length > 0, 'admin payment methods failed');
  const normalAdminAttempt = await request('/api/admin/orders', {}, userCookie);
  assert([401, 403].includes(normalAdminAttempt.response.status), 'normal user reached admin API');
  const normalDeleteAttempt = await request(`/api/admin/users/${secondUserId}`, { method: 'DELETE' }, referred.cookie);
  assert([401, 403].includes(normalDeleteAttempt.response.status), 'normal user reached admin deletion API');
  const editedUser = await patch(`/api/admin/users/${secondUserId}`, { name: 'E2E Managed User', email: `e2e-managed-${Date.now()}@example.invalid` }, adminCookie);
  assert(editedUser.response.ok && editedUser.data.user.name === 'E2E Managed User', `admin user edit failed (${editedUser.response.status}): ${editedUser.data.error || 'unexpected response'}`);

  const tempPlan = await post('/api/admin/plans', { name: `E2E ${Date.now()}`, investment: 10000, rate: 5, durationDays: 30, description: 'Temporary test plan' }, adminCookie);
  assert(tempPlan.response.status === 201, 'admin plan creation failed');
  tempPlanId = tempPlan.data.plan.id;
  assert(Number(tempPlan.data.plan.daily_return) === 500 && Number(tempPlan.data.plan.total_return) === 15000 && Number(tempPlan.data.plan.return_rate) === 5, 'backend plan calculation is incorrect');
  await patch(`/api/admin/plans/${tempPlanId}`, { active: false }, adminCookie);
  const tempMethod = await post('/api/admin/payment-methods', { name: `E2E Method ${Date.now()}`, details: 'Temporary test method' }, adminCookie);
  assert(tempMethod.response.status === 201, 'admin payment method creation failed');
  tempMethodId = tempMethod.data.method.id;
  const deletedFirst = await request(`/api/admin/users/${userId}`, { method: 'DELETE' }, adminCookie);
  assert(deletedFirst.response.ok, 'first device user soft deletion failed');
  const historyAfterDelete = Number((await pool.query('SELECT COUNT(*)::int AS count FROM user_devices WHERE device_hash = $1', [deviceHash])).rows[0].count);
  assert(historyAfterDelete === 2, 'device registration history was erased by account deletion');
  const blockedAfterDelete = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': testDeviceIp }, body: JSON.stringify(registrationBody(randomPhone(), randomPassword())) });
  assert(blockedAfterDelete.response.status === 409, 'deleted account incorrectly freed its device');
  const exception = await request('/api/admin/device-exceptions', { method: 'POST', body: JSON.stringify({ deviceHash, allowed: true, additionalAccounts: 1, reason: 'E2E approved exception' }) }, adminCookie);
  assert(exception.response.ok, 'admin device exception failed');
  const sameDeviceThird = await request('/api/register', { method: 'POST', headers: { 'x-forwarded-for': testDeviceIp }, body: JSON.stringify(registrationBody(randomPhone(), randomPassword())) });
  assert(sameDeviceThird.response.status === 201, 'authorized device exception did not allow registration');
  deviceThirdId = sameDeviceThird.data.user.id;
  await request('/api/admin/settings', { method: 'PUT', body: JSON.stringify({ max_accounts_per_device: 1 }) }, adminCookie);
  const deletedUser = await request(`/api/admin/users/${secondUserId}`, { method: 'DELETE' }, adminCookie);
  assert(deletedUser.response.ok && deletedUser.data.status === 'deleted', 'admin soft deletion failed');
  const deletedRow = (await pool.query('SELECT status,deleted_at FROM users WHERE id=$1', [secondUserId])).rows[0];
  const deleteAudit = (await pool.query("SELECT action,metadata FROM admin_audit_log WHERE target_user_id=$1 AND action='user_deleted' ORDER BY id DESC LIMIT 1", [secondUserId])).rows[0];
  assert(deletedRow.status === 'deleted' && deletedRow.deleted_at && deleteAudit?.metadata?.deletion_type === 'soft', 'deleted user or audit snapshot was not retained');
  const deletedLogin = await post('/api/login', { phone: referredPhone, password: referredPassword });
  assert(deletedLogin.response.status === 401, 'soft-deleted user was still able to log in');
  console.log('NEON_E2E_PASS');
} catch (error) {
  console.error(`NEON_E2E_FAIL: ${error.message}`);
  process.exitCode = 1;
} finally {
  if (tempMethodId) await pool.query('DELETE FROM payment_methods WHERE id=$1', [tempMethodId]);
  if (tempPlanId) await pool.query('DELETE FROM plans WHERE id=$1', [tempPlanId]);
  if (qualifiedOrderId) { await pool.query('UPDATE referral_rewards SET qualified_order_id = NULL WHERE qualified_order_id = $1', [qualifiedOrderId]); await pool.query('DELETE FROM orders WHERE id=$1', [qualifiedOrderId]); }
  const cleanupIds = [userId, secondUserId, deviceSecondId, deviceThirdId, adminCreatedId].filter(Boolean);
  if (cleanupIds.length) {
    await pool.query('DELETE FROM user_devices WHERE user_id = ANY($1::int[])', [cleanupIds]);
    await pool.query('DELETE FROM admin_audit_log WHERE target_user_id = ANY($1::int[]) OR actor_user_id = ANY($1::int[])', [cleanupIds]);
    await pool.query('DELETE FROM users WHERE id = ANY($1::int[])', [cleanupIds]);
  }
  if (e2eDeviceHash) await pool.query('DELETE FROM device_exceptions WHERE device_hash = $1', [e2eDeviceHash]);
  await pool.end();
}
